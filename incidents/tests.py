class IncidentTest(APITestCase):

    incident1 = None
    incident2 = None
    incident3 = None
    good_url = ''
    bad_url = ''
    delete_url = ''

    def setUp(self):
        self.incident1 = IncidentFactory.create(incident_number=20260001)
        self.incident2 = IncidentFactory.create(incident_number=20260002)
        self.incident3 = IncidentFactory.create(incident_number=20260003)
        self.good_url = reverse('api_incident_detail', kwargs={'pk': 20260001})
        self.bad_url = '/api/incident/H/'
        self.delete_url = reverse('api_incident_detail', kwargs={'pk': 20260003})

    def tearDown(self):
        # Adds confidence that table is clean and clear to use
        Clearance.objects.all().delete()
        IncidentCrimeLink.objects.all().delete()
        Incident.objects.all().delete()
        District.objects.all().delete()
        Sector.objects.all().delete()
        CensusBlockGroup.objects.all().delete()
        CouncilDistrict.objects.all().delete()
        LocationType.objects.all().delete()
        # Reset factory sequence to avoid conflicts
        IncidentFactory.reset_sequence(0)

    def test_incidentDetailReturnsSuccess(self):
        """
        Test that the incident detail endpoint returns a 200 status code
        and the correct incident number.
        """
        response = self.client.get(self.good_url, format='json')
        response.render()
        self.assertEqual(response.status_code, 200)
        data = json.loads(response.content)
        self.assertTrue('incident_number' in data)
        self.assertEqual(data['incident_number'], 20260001)

    def test_incidentDetailReturnFailOnBadPk(self):
        """
        Test that the incident detail endpoint returns a 404 status code
        when given an invalid incident number.
        """
        response = self.client.get(self.bad_url, format='json')
        self.assertEqual(response.status_code, 404)

    def test_incidentDetailDeleteIsSuccessful(self):
        """
        Test that the incident detail endpoint returns a 204 status code
        when deleting an incident.
        """
        response = self.client.delete(self.delete_url, format='json')
        self.assertEqual(response.status_code, 204)
    
    def test_createIncidentAutoCreatesClearanceWithNullValues(self):
        """
        Test that POSTing a new incident with no clearance field auto-creates
        a linked Clearance record with NOT_CLEARED status and null date/timestamp.
        """
        url = reverse('api_incident_detail', kwargs={'pk': 20260004})
        payload = {
            'family_violence': False,
            'occ_date': '2026-06-01',
            'occ_time': '10:00:00',
            'rep_date': '2026-06-01',
            'rep_time': '11:00:00',
        }
        response = self.client.post(url, payload, format='json')
        self.assertEqual(response.status_code, 201)

        # Verify the incident was created
        new_incident = Incident.objects.order_by('-incident_number').first()
        self.assertIsNotNone(new_incident)
        
        # Verify the linked clearance was created with default values
        clearance = Clearance.objects.get(incident=new_incident)
        self.assertEqual(clearance.clearance_status, Clearance.Status.NOT_CLEARED)
        self.assertIsNone(clearance.clearance_date)
        self.assertIsNone(clearance.last_updated)

    def test_incidentNumberIsAutoGenerated(self):
        """
        Test that POSTing a new incident auto-generates incident_number
        as max(existing incident_number) + 1.

        This test verifies that the auto-increment logic in the Incident model works correctly.
        - We expect the auto-generated number to be 20260004 (max of all in ds [20260001, 20260002, 20260003]) + 1
        """
        url = reverse('api_incident_detail', kwargs={'pk': 20260004})
        payload = {
            'family_violence': False,
            'occ_date': '2026-06-01',
            'occ_time': '10:00:00',
            'rep_date': '2026-06-01',
            'rep_time': '11:00:00',
        }
        response = self.client.post(url, payload, format='json')
        self.assertEqual(response.status_code, 201)
        data = json.loads(response.content)
        self.assertEqual(data['incident_number'], 20260004)

    def test_createIncidentMissingRequiredFields(self):
        """
        Test that POSTing with missing required fields returns 400.

        Missing: family_violence, occ_date, occ_time, rep_date, rep_time
        """
        url = reverse('api_incident_detail', kwargs={'pk': 20260004})
